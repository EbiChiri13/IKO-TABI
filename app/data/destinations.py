def place_band(place_type: str, price: int) -> int:
    """料金の目安から予算帯（0〜3）を決める。"""
    limits = {
        "lodging": (9000, 15000, 23000),  # 1泊
        "food": (1200, 2500, 5000),  # 1食
        "spot": (1000, 3000, 6000),  # 入場料
    }[place_type]
    return sum(price >= x for x in limits)
